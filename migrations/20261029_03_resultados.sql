DROP POLICY IF EXISTS "resultados: bioquimico y admin cargan" ON public.resultados;
CREATE POLICY "resultados: recepcion, bioquimico y admin cargan" ON public.resultados
  FOR INSERT TO authenticated
  WITH CHECK (
    (SELECT privado.tiene_rol('admin'))
    OR ((SELECT privado.tiene_rol('recepcion', 'bioquimico')) AND (SELECT privado.ve_sucursal(privado.sucursal_de_estudio(orden_analisis_id))))
  );

DROP POLICY IF EXISTS "resultados: bioquimico y admin validan" ON public.resultados;
CREATE POLICY "resultados: recepcion, bioquimico y admin corrigen" ON public.resultados
  FOR UPDATE TO authenticated
  USING (
    (SELECT privado.tiene_rol('admin'))
    OR ((SELECT privado.tiene_rol('recepcion', 'bioquimico')) AND (SELECT privado.ve_sucursal(privado.sucursal_de_estudio(orden_analisis_id))))
  )
  WITH CHECK (
    (SELECT privado.tiene_rol('admin'))
    OR ((SELECT privado.tiene_rol('recepcion', 'bioquimico')) AND (SELECT privado.ve_sucursal(privado.sucursal_de_estudio(orden_analisis_id))))
  );

-- Un resultado pendiente que se cargó por error se puede borrar (vuelve a "sin cargar")
CREATE POLICY "resultados: recepcion, bioquimico y admin borran pendientes" ON public.resultados
  FOR DELETE TO authenticated
  USING (
    estado = 'pendiente' AND (
      (SELECT privado.tiene_rol('admin'))
      OR ((SELECT privado.tiene_rol('recepcion', 'bioquimico')) AND (SELECT privado.ve_sucursal(privado.sucursal_de_estudio(orden_analisis_id))))
    )
  );

-- 6. Guardar los resultados de una orden juntos ─
-- p_resultados: [{"orden_analisis_id": "...", "valor_numerico": 13.2, "valor_texto": null}, ...]
-- Un estudio sin valor no se guarda; si tenía un resultado pendiente, se borra.

CREATE FUNCTION public.guardar_resultados(p_orden_id uuid, p_resultados jsonb)
RETURNS integer
LANGUAGE plpgsql SET search_path = ''
AS $$
DECLARE
  v_item jsonb;
  v_estudio uuid;
  v_numero numeric;
  v_texto varchar;
  v_guardados integer := 0;
BEGIN
  IF jsonb_typeof(p_resultados) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'Formato de resultados inválido' USING ERRCODE = '22023';
  END IF;

  FOR v_item IN SELECT * FROM jsonb_array_elements(p_resultados) LOOP
    v_estudio := (v_item ->> 'orden_analisis_id')::uuid;
    v_numero := (v_item ->> 'valor_numerico')::numeric;
    v_texto := nullif(btrim(v_item ->> 'valor_texto'), '');

    IF NOT EXISTS (SELECT 1 FROM public.orden_analisis WHERE id = v_estudio AND orden_id = p_orden_id) THEN
      RAISE EXCEPTION 'El estudio no pertenece a la orden' USING ERRCODE = '22023';
    END IF;

    IF v_numero IS NULL AND v_texto IS NULL THEN
      DELETE FROM public.resultados WHERE orden_analisis_id = v_estudio AND estado = 'pendiente';
      CONTINUE;
    END IF;

    INSERT INTO public.resultados AS r (orden_analisis_id, valor_numerico, valor_texto)
    VALUES (v_estudio, v_numero, v_texto)
    ON CONFLICT (orden_analisis_id) DO UPDATE
      SET valor_numerico = excluded.valor_numerico, valor_texto = excluded.valor_texto
      WHERE r.valor_numerico IS DISTINCT FROM excluded.valor_numerico
         OR r.valor_texto IS DISTINCT FROM excluded.valor_texto;
    v_guardados := v_guardados + 1;
  END LOOP;

  RETURN v_guardados;
END;
$$;

REVOKE ALL ON FUNCTION public.guardar_resultados(uuid, jsonb) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.rango_de_estudio(uuid) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.rangos_de_orden(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.guardar_resultados(uuid, jsonb) TO authenticated;
GRANT EXECUTE ON FUNCTION public.rango_de_estudio(uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.rangos_de_orden(uuid) TO authenticated;

REVOKE ALL ON ALL FUNCTIONS IN SCHEMA privado FROM PUBLIC;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA privado TO authenticated;
