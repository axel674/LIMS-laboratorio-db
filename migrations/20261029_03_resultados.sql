-- Carga de resultados y valores fuera de rango (LIMS-12 y LIMS-13)
--
-- Relevamiento (28 y 29/10/2026):
-- - El técnico procesa los estudios y los anota en una netbook o tablet. Los
--   resultados los carga RECEPCIÓN en el sistema (después de las 10, cuando ya no
--   hay extracciones) y también puede cargarlos el BIOQUÍMICO por alguna
--   eventualidad. Solo el bioquímico valida (LIMS-14).
-- - Un resultado se corrige mientras está pendiente; una vez validado queda fijo.
--   Se guarda quién lo cargó y cuándo.
-- - Los valores de referencia dependen del sexo y la edad del paciente. Se usa el
--   rango más específico que corresponda; si no hay ninguno, el general del
--   catálogo. Los valores cargados acá son orientativos (fuentes públicas): los
--   confirma o ajusta el bioquímico.
-- - Cada resultado guarda el rango con el que se comparó, para que el informe
--   muestre el mismo aunque después cambie el catálogo.

-- 1. Rangos por sexo y edad ────────────────────

CREATE TABLE public.analisis_rangos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  analisis_id bigint NOT NULL REFERENCES public.analisis(id),
  sexo public.sexo,
  edad_desde smallint NOT NULL DEFAULT 0 CHECK (edad_desde >= 0),
  edad_hasta smallint CHECK (edad_hasta IS NULL OR edad_hasta > edad_desde),
  valor_min numeric,
  valor_max numeric,
  CHECK (valor_min IS NOT NULL OR valor_max IS NOT NULL),
  CHECK (valor_min IS NULL OR valor_max IS NULL OR valor_min <= valor_max)
);
CREATE INDEX analisis_rangos_analisis_id_idx ON public.analisis_rangos (analisis_id);

COMMENT ON TABLE public.analisis_rangos IS
  'Valores de referencia por sexo y edad. Si no hay uno que corresponda al paciente, se usa el general del catálogo (analisis.valor_ref_min/max).';
COMMENT ON COLUMN public.analisis_rangos.sexo IS 'Vacío = para todos los sexos.';
COMMENT ON COLUMN public.analisis_rangos.edad_desde IS 'Edad en años desde la que aplica (incluida).';
COMMENT ON COLUMN public.analisis_rangos.edad_hasta IS 'Edad en años hasta la que aplica (sin incluir). Vacío = sin límite.';

