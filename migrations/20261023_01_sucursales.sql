-- Sucursales
--
-- Relevamiento (23/10/2026): el laboratorio tiene más de una sucursal.
-- - Todavía no están definidos los nombres: se cargan dos provisorias (S1 y S2)
--   y el administrador las renombra desde el panel.
-- - Cada persona del personal elige al entrar en qué sucursal trabaja. Por eso
--   la sucursal es un filtro de trabajo y no un límite de seguridad: el personal
--   puede ver las dos (rota entre sucursales).
-- - La fila de atención, su numeración del día y los boxes son de cada sucursal.
-- - El prefijo de la sucursal se usa en el número de orden (LIMS-10).
--
-- Compatibilidad: el frontend publicado todavía llama a registrar_llegada y
-- llamar_siguiente sin sucursal. Los parámetros nuevos tienen DEFAULT NULL y, si
-- no llegan, se usa la primera sucursal activa. La tabla configuracion
-- (cantidad_boxes) queda sin uso: los boxes pasan a sucursales.cantidad_boxes y
-- se borrará en una migración posterior, cuando el frontend nuevo esté publicado.

-- 1. Tabla ─────────────────────────────────────

CREATE TABLE public.sucursales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar NOT NULL UNIQUE CHECK (btrim(nombre) <> ''),
  prefijo varchar NOT NULL UNIQUE CHECK (prefijo ~ '^[A-Z0-9]{2,5}$'),
  direccion varchar,
  cantidad_boxes smallint NOT NULL DEFAULT 2 CHECK (cantidad_boxes BETWEEN 1 AND 20),
  activa boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.sucursales IS
  'Sucursales del laboratorio. Cada una tiene su fila de atención, sus boxes y su numeración de órdenes.';
COMMENT ON COLUMN public.sucursales.prefijo IS
  'Va al comienzo del número de orden (ej: S1-2026-000123). De 2 a 5 letras mayúsculas o números.';
COMMENT ON COLUMN public.sucursales.cantidad_boxes IS 'Boxes de extracción habilitados (Box 1 a Box N).';

-- Los boxes que ya se habían configurado pasan a la primera sucursal
INSERT INTO public.sucursales (nombre, prefijo, cantidad_boxes)
SELECT 'Sucursal 1', 'S1', coalesce((SELECT cantidad_boxes FROM public.configuracion), 2)
UNION ALL
SELECT 'Sucursal 2', 'S2', 2;

ALTER TABLE public.sucursales ENABLE ROW LEVEL SECURITY;

CREATE POLICY "sucursales: lectura del personal" ON public.sucursales
  FOR SELECT TO authenticated USING ((SELECT privado.es_personal()));
CREATE POLICY "sucursales: admin da de alta" ON public.sucursales
  FOR INSERT TO authenticated WITH CHECK ((SELECT privado.tiene_rol('admin')));
CREATE POLICY "sucursales: admin modifica" ON public.sucursales
  FOR UPDATE TO authenticated
  USING ((SELECT privado.tiene_rol('admin'))) WITH CHECK ((SELECT privado.tiene_rol('admin')));
-- No se borran: una sucursal que cierra se desactiva (activa = false)

-- Sucursal que usan las funciones cuando no se indica ninguna
CREATE FUNCTION privado.sucursal_por_defecto()
RETURNS bigint
LANGUAGE sql STABLE SET search_path = ''
AS $$
  SELECT id FROM public.sucursales WHERE activa ORDER BY id LIMIT 1;
$$;

-- 2. Fila de atención por sucursal ────────────

ALTER TABLE public.turnos ADD COLUMN sucursal_id bigint REFERENCES public.sucursales (id);
UPDATE public.turnos SET sucursal_id = privado.sucursal_por_defecto();
ALTER TABLE public.turnos ALTER COLUMN sucursal_id SET NOT NULL;

-- El número del día pasa a ser por sucursal. Un paciente sigue registrándose una
-- sola vez por día (no puede estar en las dos filas a la vez).
ALTER TABLE public.turnos DROP CONSTRAINT turnos_numero_por_dia;
ALTER TABLE public.turnos ADD CONSTRAINT turnos_numero_por_dia UNIQUE (sucursal_id, fecha, numero);
DROP INDEX public.turnos_fila_del_dia;
CREATE INDEX turnos_fila_del_dia ON public.turnos (sucursal_id, fecha, estado, numero);

COMMENT ON COLUMN public.turnos.numero IS 'Número de atención; se reinicia cada día en cada sucursal.';

-- 3. Funciones con sucursal ───────────────────
-- Se reemplazan con un parámetro más al final (DEFAULT NULL): las llamadas que no
-- lo mandan siguen funcionando con la sucursal por defecto.

DROP FUNCTION public.registrar_llegada(uuid, public.tipo_extraccion, text);
CREATE FUNCTION public.registrar_llegada(
  p_paciente_id uuid,
  p_tipo public.tipo_extraccion DEFAULT 'ambulatoria',
  p_observaciones text DEFAULT NULL,
  p_sucursal_id bigint DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_hoy date := privado.hoy();
  v_sucursal bigint := coalesce(p_sucursal_id, privado.sucursal_por_defecto());
  v_turno public.turnos;
BEGIN
  IF NOT privado.tiene_rol('recepcion', 'admin') THEN
    RAISE EXCEPTION 'Solo recepción puede registrar llegadas' USING ERRCODE = '42501';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.sucursales WHERE id = v_sucursal AND activa) THEN
    RAISE EXCEPTION 'La sucursal no existe o no está activa' USING ERRCODE = '22023';
  END IF;

  PERFORM privado.cerrar_dias_anteriores();

  -- Un registro a la vez por sucursal y día: dos recepcionistas nunca reciben el mismo número
  PERFORM pg_advisory_xact_lock(hashtext('turnos:' || v_sucursal || ':' || v_hoy));

  -- Si ya estaba registrado hoy (en cualquier sucursal) se devuelve ese turno
  SELECT * INTO v_turno FROM public.turnos WHERE paciente_id = p_paciente_id AND fecha = v_hoy;
  IF FOUND THEN
    RETURN jsonb_build_object('turno', to_jsonb(v_turno), 'ya_registrado', true);
  END IF;

  INSERT INTO public.turnos (paciente_id, sucursal_id, fecha, numero, tipo, observaciones, registrado_por)
  VALUES (
    p_paciente_id,
    v_sucursal,
    v_hoy,
    (SELECT coalesce(max(numero), 0) + 1 FROM public.turnos WHERE sucursal_id = v_sucursal AND fecha = v_hoy),
    coalesce(p_tipo, 'ambulatoria'),
    nullif(btrim(p_observaciones), ''),
    auth.uid()
  )
  RETURNING * INTO v_turno;

  RETURN jsonb_build_object('turno', to_jsonb(v_turno), 'ya_registrado', false);
END;
$$;

DROP FUNCTION public.llamar_siguiente(smallint);
CREATE FUNCTION public.llamar_siguiente(p_box smallint, p_sucursal_id bigint DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_hoy date := privado.hoy();
  v_sucursal bigint := coalesce(p_sucursal_id, privado.sucursal_por_defecto());
  v_boxes smallint;
  v_turno public.turnos;
BEGIN
  IF NOT privado.tiene_rol('tecnico', 'bioquimico', 'admin') THEN
    RAISE EXCEPTION 'Solo extracción puede llamar pacientes' USING ERRCODE = '42501';
  END IF;

  SELECT cantidad_boxes INTO v_boxes FROM public.sucursales WHERE id = v_sucursal AND activa;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'La sucursal no existe o no está activa' USING ERRCODE = '22023';
  END IF;
  IF p_box IS NULL OR p_box < 1 OR p_box > v_boxes THEN
    RAISE EXCEPTION 'El box % no existe en esta sucursal', p_box USING ERRCODE = '22023';
  END IF;

  PERFORM privado.cerrar_dias_anteriores();

  -- Si este box ya tiene a alguien llamado sin terminar, se devuelve ese mismo
  SELECT * INTO v_turno FROM public.turnos
  WHERE sucursal_id = v_sucursal AND fecha = v_hoy AND estado = 'llamado' AND box = p_box
  ORDER BY llamado_at
  LIMIT 1;
  IF FOUND THEN
    RETURN to_jsonb(v_turno);
  END IF;

  -- SKIP LOCKED: si dos boxes llaman a la vez, cada uno se lleva a un paciente distinto
  SELECT * INTO v_turno FROM public.turnos
  WHERE sucursal_id = v_sucursal AND fecha = v_hoy AND estado = 'en_espera'
  ORDER BY numero
  LIMIT 1
  FOR UPDATE SKIP LOCKED;
  IF NOT FOUND THEN
    RETURN NULL;
  END IF;

  UPDATE public.turnos
  SET estado = 'llamado', box = p_box, llamado_por = auth.uid(), llamado_at = now()
  WHERE id = v_turno.id
  RETURNING * INTO v_turno;

  RETURN to_jsonb(v_turno);
END;
$$;

REVOKE EXECUTE ON FUNCTION public.registrar_llegada(uuid, public.tipo_extraccion, text, bigint) FROM PUBLIC, anon;
REVOKE EXECUTE ON FUNCTION public.llamar_siguiente(smallint, bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.registrar_llegada(uuid, public.tipo_extraccion, text, bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION public.llamar_siguiente(smallint, bigint) TO authenticated;
