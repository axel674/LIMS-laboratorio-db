-- Recuperar y restablecer contraseñas (LIMS-45)
--
-- Queda registrado cada cambio de contraseña que no hace la persona desde su sesión:
-- - panel: recepción o el admin le dan una contraseña provisoria nueva (Edge Function
--   restablecer-password). La persona tiene que cambiarla en su siguiente ingreso.
-- - mail_pedido: un paciente pidió el link para restablecerla desde el login del portal
--   (Edge Function recuperar-password). También sirve para no mandar más de un mail
--   cada 5 minutos.
-- - mail: el paciente eligió su contraseña nueva desde ese link.
--
-- Las filas las escriben las Edge Functions con la clave secreta y la función
-- completar_recuperacion_password. Solo el admin las lee.

-- 1. Registro ──────────────────────────────────

CREATE TYPE public.via_cambio_password AS ENUM ('panel', 'mail_pedido', 'mail');

CREATE TABLE public.cambios_password (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  perfil_id uuid NOT NULL REFERENCES public.perfiles (id) ON DELETE CASCADE,
  via public.via_cambio_password NOT NULL,
  -- Quién la restableció desde el panel; vacío cuando lo hace el paciente por mail
  hecho_por uuid REFERENCES public.perfiles (id),
  creado_en timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX cambios_password_perfil_idx ON public.cambios_password (perfil_id, creado_en DESC);

COMMENT ON TABLE public.cambios_password IS
  'Contraseñas restablecidas desde el panel o recuperadas por mail (LIMS-45): a quién, quién lo hizo, cuándo y por qué vía.';
COMMENT ON COLUMN public.cambios_password.via IS
  'panel: provisoria nueva dada por recepción o el admin · mail_pedido: el paciente pidió el link · mail: la cambió desde el link.';

ALTER TABLE public.cambios_password ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.cambios_password FROM anon, authenticated;
GRANT SELECT ON public.cambios_password TO authenticated;

CREATE POLICY "cambios_password: los lee el admin" ON public.cambios_password
  FOR SELECT TO authenticated
  USING ((SELECT privado.tiene_rol('admin')));

-- 2. Cierre de la recuperación por mail ────────
-- El paciente entra con el link, elige su contraseña (supabase.auth.updateUser) y llama
-- a esta función: queda registrado y deja de pedirse el cambio de la provisoria.
-- Solo vale si pidió el link en la última hora (lo que dura el link) y después de la
-- última provisoria que le dieron desde el panel: así nadie se saltea ese cambio.

CREATE FUNCTION public.completar_recuperacion_password()
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_pedido timestamptz;
  v_panel timestamptz;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Sesión inválida' USING ERRCODE = '42501';
  END IF;

  SELECT max(creado_en) FILTER (WHERE via = 'mail_pedido'),
         max(creado_en) FILTER (WHERE via = 'panel')
    INTO v_pedido, v_panel
    FROM public.cambios_password
   WHERE perfil_id = auth.uid();

  IF v_pedido IS NULL OR v_pedido < now() - interval '1 hour'
     OR (v_panel IS NOT NULL AND v_panel > v_pedido) THEN
    RAISE EXCEPTION 'No hay un pedido de recuperación vigente' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.cambios_password (perfil_id, via, hecho_por)
  VALUES (auth.uid(), 'mail', auth.uid());

  UPDATE public.perfiles SET debe_cambiar_password = false WHERE id = auth.uid();
END;
$$;

REVOKE ALL ON FUNCTION public.completar_recuperacion_password() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.completar_recuperacion_password() TO authenticated;
